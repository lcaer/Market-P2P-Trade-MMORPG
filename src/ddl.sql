CREATE TABLE P2P_MOVIMENTACAO (
    ID_MOVIMENTACAO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    DESCRICAO VARCHAR(200) NOT NULL,
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_P2P_MOVIMENTACAO PRIMARY KEY (ID_MOVIMENTACAO)
);

CREATE TABLE P2P_TABELA_ALVO (
    ID_TABELA INTEGER NOT NULL,
    NOME VARCHAR2(30) NOT NULL,
    PK VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_P2P_TABELA_ALVO PRIMARY KEY (ID_TABELA),
    CONSTRAINT UK_P2P_TABELA_ALVO_NOME UNIQUE (NOME)
);

CREATE TABLE P2P_CATEGORIA (
    ID_CATEGORIA INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2),
    NOME VARCHAR2(20) NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = matéria-prima, 1 = produto
    CONSTRAINT PK_P2P_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_P2P_CATEGORIA_NOME UNIQUE (NOME),
    CONSTRAINT CK_P2P_CATEGORIA_TIPO
        CHECK (TIPO BETWEEN 0 AND 1),
    CONSTRAINT CK_P2P_CATEGORIA_NOME_VAZIO
        CHECK (TRIM(NOME) IS NOT NULL)
);

CREATE TABLE P2P_ITEM (
    ID_ITEM INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2),
    ID_CATEGORIA INTEGER NOT NULL,
    RARIDADE NUMBER(1,0) NOT NULL, -- 1 = comum, 2 = raro, 3 = lendário, 4 = divino
    NOME VARCHAR2(20) NOT NULL,
    DESCRICAO VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_P2P_ITEM PRIMARY KEY (ID_ITEM),
    CONSTRAINT UK_P2P_ITEM_NOME UNIQUE (NOME),
    CONSTRAINT FK_P2P_ITEM_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES P2P_CATEGORIA (ID_CATEGORIA),
    CONSTRAINT CK_P2P_ITEM_RARIDADE
        CHECK (RARIDADE BETWEEN 1 AND 4),
    CONSTRAINT CK_P2P_ITEM_NOME_VAZIO
        CHECK (TRIM(NOME) IS NOT NULL),
    CONSTRAINT CK_P2P_ITEM_DESCRICAO_VAZIA
        CHECK (TRIM(DESCRICAO) IS NOT NULL)
);

CREATE TABLE P2P_USUARIO (
    ID_USUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    NOME VARCHAR2(100) NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    SENHA VARCHAR2(16) NOT NULL,
    CONSTRAINT PK_P2P_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_P2P_USUARIO_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_P2P_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_P2P_USUARIO_EMAIL_FORMATO
        CHECK (REGEXP_LIKE(EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
    CONSTRAINT CK_P2P_USUARIO_USERNAME_FORMATO
        CHECK (REGEXP_LIKE(USERNAME, '^[A-Za-z0-9_]{3,20}$')),
    CONSTRAINT CK_P2P_USUARIO_NOME_VAZIO
        CHECK (TRIM(NOME) IS NOT NULL),
    CONSTRAINT CK_P2P_USUARIO_SENHA_TAMANHO
        CHECK (LENGTH(SENHA) >= 8),
    CONSTRAINT CK_P2P_USUARIO_SENHA_ESPACO
        CHECK (INSTR(SENHA, ' ') = 0),
    CONSTRAINT CK_P2P_USUARIO_SENHA_IGUAL_USERNAME
        CHECK (SENHA <> USERNAME)
);

CREATE TABLE P2P_PERSONAGEM (
    ID_PERSONAGEM INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_USUARIO INTEGER,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = jogador, 1 = NPC
    NICKNAME VARCHAR2(100) NOT NULL,
    NIVEL NUMBER(3,0) NULL,
    CONSTRAINT PK_P2P_PERSONAGEM PRIMARY KEY (ID_PERSONAGEM),
    CONSTRAINT UK_P2P_PERSONAGEM_NICKNAME UNIQUE (NICKNAME),
    CONSTRAINT UK_P2P_PERSONAGEM_ID_TIPO UNIQUE (ID_PERSONAGEM, TIPO),
    CONSTRAINT FK_P2P_PERSONAGEM_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES P2P_USUARIO (ID_USUARIO),
    CONSTRAINT CK_P2P_PERSONAGEM_TIPO
        CHECK (TIPO BETWEEN 0 AND 1),
    CONSTRAINT CK_P2P_PERSONAGEM_JOGADOR_USUARIO
        CHECK (TIPO <> 0 OR ID_USUARIO IS NOT NULL),
    CONSTRAINT CK_P2P_PERSONAGEM_JOGADOR_NIVEL_OBRIGATORIO
        CHECK (TIPO <> 0 OR NIVEL IS NOT NULL),
    CONSTRAINT CK_P2P_PERSONAGEM_NPC_SEM_USUARIO
        CHECK (TIPO <> 1 OR ID_USUARIO IS NULL),
    CONSTRAINT CK_P2P_PERSONAGEM_NPC_SEM_NIVEL
        CHECK (TIPO <> 1 OR NIVEL IS NULL)
);

CREATE TABLE P2P_ESPOLIO (
    ID_ESPOLIO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_PERSONAGEM INTEGER NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = jogador, 1 = NPC
    ID_ITEM INTEGER NOT NULL,
    PROBABILIDADE NUMBER(3,0),
    QNT NUMBER(3,0),
    QNT_MIN NUMBER(3,0),
    QNT_MAX NUMBER(3,0),
    CONSTRAINT PK_P2P_ESPOLIO PRIMARY KEY (ID_ESPOLIO),
    CONSTRAINT UK_P2P_ESPOLIO_PERSONAGEM_ITEM UNIQUE (ID_PERSONAGEM, ID_ITEM),
    CONSTRAINT FK_P2P_ESPOLIO_PERSONAGEM FOREIGN KEY (ID_PERSONAGEM, TIPO)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM, TIPO),
    CONSTRAINT FK_P2P_ESPOLIO_ITEM FOREIGN KEY (ID_ITEM)
        REFERENCES P2P_ITEM (ID_ITEM),
    CONSTRAINT CK_P2P_ESPOLIO_TIPO
        CHECK (TIPO IN (0, 1)),
    CONSTRAINT CK_P2P_ESPOLIO_JOGADOR_QNT_OBRIGATORIA
        CHECK (TIPO <> 0 OR QNT IS NOT NULL),
    CONSTRAINT CK_P2P_ESPOLIO_JOGADOR_QNT_NAO_NEGATIVA
        CHECK (TIPO <> 0 OR QNT >= 0),
    CONSTRAINT CK_P2P_ESPOLIO_JOGADOR_SEM_PROBABILIDADE
        CHECK (TIPO <> 0 OR PROBABILIDADE IS NULL),
    CONSTRAINT CK_P2P_ESPOLIO_JOGADOR_SEM_FAIXA_QNT
        CHECK (TIPO <> 0 OR (QNT_MIN IS NULL AND QNT_MAX IS NULL)),
    CONSTRAINT CK_P2P_ESPOLIO_NPC_SEM_QNT
        CHECK (TIPO <> 1 OR QNT IS NULL),
    CONSTRAINT CK_P2P_ESPOLIO_NPC_PROBABILIDADE_OBRIGATORIA
        CHECK (TIPO <> 1 OR PROBABILIDADE IS NOT NULL),
    CONSTRAINT CK_P2P_ESPOLIO_NPC_PROBABILIDADE_FAIXA
        CHECK (TIPO <> 1 OR PROBABILIDADE BETWEEN 1 AND 100),
    CONSTRAINT CK_P2P_ESPOLIO_NPC_QNT_MIN_OBRIGATORIO
        CHECK (TIPO <> 1 OR QNT_MIN IS NOT NULL),
    CONSTRAINT CK_P2P_ESPOLIO_NPC_QNT_MIN_POSITIVO
        CHECK (TIPO <> 1 OR QNT_MIN >= 1),
    CONSTRAINT CK_P2P_ESPOLIO_NPC_QNT_MAX_COERENTE
        CHECK (TIPO <> 1 OR QNT_MAX >= QNT_MIN)
);

CREATE TABLE P2P_ANUNCIO (
    ID_ANUNCIO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_ANUNCIANTE INTEGER NOT NULL,
    ID_INTERESSADO INTEGER,
    TIPO NUMBER(1,0) NOT NULL, -- 1 = venda, 2 = compra, 3 = leilão
    TITULO VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(200),
    STATUS NUMBER(1,0) DEFAULT 1 NOT NULL, -- 1 = aberto, 2 = fechado, 3 = cancelado
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    FECHADO_EM DATE,
    LANCE_DIRETO NUMBER(3,0),
    MIN_LANCE NUMBER(3,0),
    CONSTRAINT PK_P2P_ANUNCIO PRIMARY KEY (ID_ANUNCIO),
    CONSTRAINT FK_P2P_ANUNCIO_ANUNCIANTE
        FOREIGN KEY (ID_ANUNCIANTE)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_ANUNCIO_INTERESSADO
        FOREIGN KEY (ID_INTERESSADO)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT CK_P2P_ANUNCIO_TIPO
        CHECK (TIPO BETWEEN 1 AND 3),
    CONSTRAINT CK_P2P_ANUNCIO_STATUS
        CHECK (STATUS BETWEEN 1 AND 3),
    CONSTRAINT CK_P2P_ANUNCIO_TITULO
        CHECK (TRIM(TITULO) IS NOT NULL
               AND TITULO = TRIM(TITULO)),
    CONSTRAINT CK_P2P_ANUNCIO_DESCRICAO
        CHECK (DESCRICAO IS NULL OR TRIM(DESCRICAO) IS NOT NULL),
    CONSTRAINT CK_P2P_ANUNCIO_ABERTO
        CHECK (STATUS <> 1
               OR (ID_INTERESSADO IS NULL AND FECHADO_EM IS NULL)),
    CONSTRAINT CK_P2P_ANUNCIO_FECHADO
        CHECK (STATUS <> 2
               OR (ID_INTERESSADO IS NOT NULL
                   AND FECHADO_EM IS NOT NULL
                   AND FECHADO_EM >= CRIADO_EM)),
    CONSTRAINT CK_P2P_ANUNCIO_PARTICIPANTES_DIFERENTES
        CHECK (ID_INTERESSADO IS NULL
               OR ID_ANUNCIANTE <> ID_INTERESSADO),
    CONSTRAINT CK_P2P_ANUNCIO_LEILAO_MIN_LANCE
        CHECK (TIPO <> 3
               OR (MIN_LANCE IS NOT NULL AND MIN_LANCE > 0)),
    CONSTRAINT CK_P2P_ANUNCIO_LEILAO_LANCE_DIRETO
        CHECK (TIPO <> 3
               OR LANCE_DIRETO IS NULL
               OR LANCE_DIRETO >= MIN_LANCE),
    CONSTRAINT CK_P2P_ANUNCIO_NAO_LEILAO_SEM_LANCES
        CHECK (TIPO = 3
               OR (LANCE_DIRETO IS NULL AND MIN_LANCE IS NULL))
);

CREATE TABLE P2P_ANUNCIO_ITEM (
    ID_ANUNCIO_ITEM INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_ANUNCIO INTEGER NOT NULL,
    ID_ITEM INTEGER NOT NULL,
    ACAO NUMBER(1,0) NOT NULL, -- 0 = ofertado, 1 = solicitado
    QNT NUMBER(3,0) NOT NULL,
    CONSTRAINT PK_P2P_ANUNCIO_ITEM PRIMARY KEY (ID_ANUNCIO_ITEM),
    CONSTRAINT FK_P2P_ANUNCIO_ITEM_ANUNCIO FOREIGN KEY (ID_ANUNCIO)
        REFERENCES P2P_ANUNCIO (ID_ANUNCIO),
    CONSTRAINT FK_P2P_ANUNCIO_ITEM_ITEM FOREIGN KEY (ID_ITEM)
        REFERENCES P2P_ITEM (ID_ITEM),
    CONSTRAINT UK_P2P_ANUNCIO_ITEM_ANUNCIO_ITEM_ACAO
        UNIQUE (ID_ANUNCIO, ID_ITEM, ACAO),
    CONSTRAINT CK_P2P_ANUNCIO_ITEM_ACAO
        CHECK (ACAO BETWEEN 0 AND 1),
    CONSTRAINT CK_P2P_ANUNCIO_ITEM_QNT_POSITIVA
        CHECK (QNT > 0)
);

CREATE TABLE P2P_OCORRENCIA (
    ID_OCORRENCIA INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_MOVIMENTACAO INTEGER NOT NULL,
    DESCRICAO VARCHAR(200) NOT NULL,
    ID_ORIGEM INTEGER, 
    ID_DESTINO INTEGER, 
    ID_TABELA INTEGER,
    ID_REGISTRO INTEGER, 
    ID_ESPOLIO INTEGER,
    ID_ANUNCIO_ITEM INTEGER,
    QNT NUMBER(3,0),
    CONSTRAINT PK_P2P_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT UK_P2P_OCORRENCIA_ANUNCIO_ITEM UNIQUE (ID_ANUNCIO_ITEM),
    CONSTRAINT FK_P2P_OCORRENCIA_MOVIMENTACAO FOREIGN KEY (ID_MOVIMENTACAO)
        REFERENCES P2P_MOVIMENTACAO (ID_MOVIMENTACAO),
    CONSTRAINT FK_P2P_OCORRENCIA_ORIGEM FOREIGN KEY (ID_ORIGEM)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_OCORRENCIA_DESTINO FOREIGN KEY (ID_DESTINO)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_OCORRENCIA_TABELA FOREIGN KEY (ID_TABELA)
        REFERENCES P2P_TABELA_ALVO (ID_TABELA),
    CONSTRAINT FK_P2P_OCORRENCIA_ESPOLIO FOREIGN KEY (ID_ESPOLIO)
        REFERENCES P2P_ESPOLIO (ID_ESPOLIO),
    CONSTRAINT FK_P2P_OCORRENCIA_ANUNCIO_ITEM FOREIGN KEY (ID_ANUNCIO_ITEM)
        REFERENCES P2P_ANUNCIO_ITEM (ID_ANUNCIO_ITEM),
    CONSTRAINT CK_P2P_OCORRENCIA_DESTINO_XOR
        CHECK ((ID_DESTINO IS NOT NULL AND ID_TABELA IS NULL)
               OR (ID_DESTINO IS NULL AND ID_TABELA IS NOT NULL)),
    CONSTRAINT CK_P2P_OCORRENCIA_TABELA_REGISTRO_JUNTOS
        CHECK ((ID_TABELA IS NULL AND ID_REGISTRO IS NULL)
               OR (ID_TABELA IS NOT NULL AND ID_REGISTRO IS NOT NULL)),
    CONSTRAINT CK_P2P_OCORRENCIA_ORIGEM_DESTINO_DIFERENTES
        CHECK (ID_ORIGEM IS NULL OR ID_DESTINO IS NULL OR ID_ORIGEM <> ID_DESTINO),
    CONSTRAINT CK_P2P_OCORRENCIA_SISTEMA_SEM_ORIGEM
        CHECK (ID_DESTINO IS NOT NULL OR ID_ORIGEM IS NULL),
    CONSTRAINT CK_P2P_OCORRENCIA_SEM_ORIGEM_SEM_CAUSA
        CHECK (ID_ORIGEM IS NOT NULL OR (ID_ESPOLIO IS NULL AND ID_ANUNCIO_ITEM IS NULL)),
    CONSTRAINT CK_P2P_OCORRENCIA_ORIGEM_UMA_CAUSA
        CHECK (ID_ORIGEM IS NULL
               OR (ID_ESPOLIO IS NOT NULL AND ID_ANUNCIO_ITEM IS NULL)
               OR (ID_ESPOLIO IS NULL AND ID_ANUNCIO_ITEM IS NOT NULL)),
    CONSTRAINT CK_P2P_OCORRENCIA_QNT_POSITIVA
        CHECK (QNT IS NULL OR QNT > 0),
    CONSTRAINT CK_P2P_OCORRENCIA_QNT_OBRIGATORIA_COMUM
        CHECK (ID_DESTINO IS NULL OR QNT IS NOT NULL),
    CONSTRAINT CK_P2P_OCORRENCIA_QNT_PROIBIDA_SISTEMA
        CHECK (ID_DESTINO IS NOT NULL OR QNT IS NULL)
);

CREATE TABLE P2P_HISTORICO_NEGOCIO (
    ID_HISTORICO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    ID_ANUNCIO INTEGER NOT NULL,
    ID_PERSONAGEM INTEGER NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = anunciante, 1 = interessado
    MENSAGEM VARCHAR2(200) NOT NULL,
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_P2P_HISTORICO_NEGOCIO PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_P2P_HISTORICO_NEGOCIO_ANUNCIO FOREIGN KEY (ID_ANUNCIO)
        REFERENCES P2P_ANUNCIO (ID_ANUNCIO),
    CONSTRAINT FK_P2P_HISTORICO_NEGOCIO_AUTOR FOREIGN KEY (ID_PERSONAGEM)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT CK_P2P_HISTORICO_NEGOCIO_TIPO
        CHECK (TIPO BETWEEN 0 AND 1),
    CONSTRAINT CK_P2P_HISTORICO_NEGOCIO_MENSAGEM_VAZIA
        CHECK (TRIM(MENSAGEM) IS NOT NULL)
);

