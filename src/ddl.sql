CREATE TABLE P2P_USUARIO (
    ID_USUARIO INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    NOME VARCHAR2(100) NOT NULL,
    USERNAME VARCHAR2(20) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    SENHA VARCHAR2(16) NOT NULL,
    CONSTRAINT PK_P2P_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_P2P_USUARIO_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_P2P_USUARIO_EMAIL UNIQUE (EMAIL),

    CONSTRAINT CK_P2P_USUARIO_REGRAS CHECK (
        -- Email em formato válido.
        REGEXP_LIKE(EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')
        AND
        -- Username: 3-20 letras, números ou _.
        REGEXP_LIKE(USERNAME, '^[A-Za-z0-9_]{3,20}$')
        AND
        -- Nome não pode ser vazio.
        TRIM(NOME) IS NOT NULL
        AND
        -- Senha com mínimo de 8 caracteres.
        LENGTH(SENHA) >= 8
        AND
        -- Senha sem espaços.
        INSTR(SENHA, ' ') = 0
        AND
        -- Senha diferente do username.
        SENHA <> USERNAME
    )
);

CREATE TABLE P2P_CATEGORIA (
    ID_CATEGORIA INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    COD_CATEGORIA VARCHAR2(5) NOT NULL,
    NOME VARCHAR2(20) NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = matéria-prima, 1 = produto
    CONSTRAINT PK_P2P_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_P2P_CATEGORIA_COD_CATEGORIA UNIQUE (COD_CATEGORIA),
    CONSTRAINT UK_P2P_CATEGORIA_NOME UNIQUE (NOME),

    CONSTRAINT CK_P2P_CATEGORIA_REGRAS CHECK (
        -- Tipo: 0 ou 1.
        TIPO BETWEEN 0 AND 1
        AND
        -- Código: 2-5 letras maiúsculas ou números.
        REGEXP_LIKE(COD_CATEGORIA, '^[A-Z0-9]{2,5}$')
        AND
        -- Nome não pode ser vazio.
        TRIM(NOME) IS NOT NULL
    )
);

CREATE TABLE P2P_MOVIMENTACAO (
    ID_MOVIMENTACAO INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_P2P_MOVIMENTACAO PRIMARY KEY (ID_MOVIMENTACAO)
);

CREATE TABLE P2P_PERSONAGEM (
    ID_PERSONAGEM INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    ID_USUARIO INTEGER,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = jogador, 1 = NPC
    NICKNAME VARCHAR2(100) NOT NULL,
    COD_NPC VARCHAR2(3) NULL,
    NIVEL NUMBER(3,0) NULL,
    
    CONSTRAINT PK_P2P_PERSONAGEM PRIMARY KEY (ID_PERSONAGEM),
    CONSTRAINT UK_P2P_PERSONAGEM_NICKNAME UNIQUE (NICKNAME),
    CONSTRAINT UK_P2P_PERSONAGEM_ID_TIPO UNIQUE (ID_PERSONAGEM, TIPO),
    CONSTRAINT FK_P2P_PERSONAGEM_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES P2P_USUARIO (ID_USUARIO),

    CONSTRAINT CK_P2P_PERSONAGEM_REGRAS CHECK (
        -- Tipo: jogador (0) ou NPC (1).
        TIPO BETWEEN 0 AND 1
        
        -- Regras exclusivas para JOGADOR (TIPO = 0)
        AND (
            (
                TIPO = 0 
                AND ID_USUARIO IS NOT NULL 
                AND COD_NPC IS NULL       -- Jogador NÃO tem cod_npc
                AND NIVEL IS NOT NULL     -- Jogador DEVE ter nível
            )
            OR
            -- Regras exclusivas para NPC (TIPO = 1)
            (
                TIPO = 1 
                AND ID_USUARIO IS NULL 
                AND COD_NPC IS NOT NULL   -- NPC DEVE ter cod_npc
                AND NIVEL IS NULL         -- NPC NÃO tem nível
                AND REGEXP_LIKE(COD_NPC, '^[A-Z0-9]{3}$') -- Valida o formato do COD_NPC
            )
        )
    )
);


CREATE TABLE P2P_ITEM (
    ID_ITEM INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2),
    ID_CATEGORIA INTEGER NOT NULL,
    COD_ITEM VARCHAR2(5) NOT NULL,
    NOME VARCHAR2(20) NOT NULL,
    RARIDADE NUMBER(1,0) NOT NULL, -- 0 = comum, 1 = raro, 2 = lendário, 3 = divino
    DESCRICAO VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_P2P_ITEM PRIMARY KEY (ID_ITEM),
    CONSTRAINT UK_P2P_ITEM_COD_ITEM UNIQUE (COD_ITEM),
    CONSTRAINT FK_P2P_ITEM_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES P2P_CATEGORIA (ID_CATEGORIA),

    CONSTRAINT CK_P2P_ITEM_REGRAS CHECK (
        -- Raridade entre 0 e 3.
        RARIDADE BETWEEN 0 AND 3
        AND
        -- Código: 3-5 letras maiúsculas ou números.
        REGEXP_LIKE(COD_ITEM, '^[A-Z0-9]{3,5}$')
        AND
        -- Nome não pode ser vazio.
        TRIM(NOME) IS NOT NULL
        AND
        -- Descrição não pode ser vazia.
        TRIM(DESCRICAO) IS NOT NULL
    )
);

CREATE TABLE P2P_ANUNCIO (
    ID_ANUNCIO INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    ID_VENDEDOR INTEGER,
    ID_COMPRADOR INTEGER,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = venda, 1 = compra, 2 = leilão
    TITULO VARCHAR2(20) NOT NULL,
    DESCRICAO VARCHAR2(200),
    STATUS NUMBER(1,0) NOT NULL, -- 0 = aberto, 1 = fechado, 2 = cancelado
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    FECHADO_EM DATE,
    LANCE_DIRETO NUMBER(3,0),
    MIN_LANCE NUMBER(3,0),
    CONSTRAINT PK_P2P_ANUNCIO PRIMARY KEY (ID_ANUNCIO),
    CONSTRAINT FK_P2P_ANUNCIO_VENDEDOR FOREIGN KEY (ID_VENDEDOR)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_ANUNCIO_COMPRADOR FOREIGN KEY (ID_COMPRADOR)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),

    CONSTRAINT CK_P2P_ANUNCIO_REGRAS CHECK (
        -- Tipo: venda, compra ou leilão.
        TIPO BETWEEN 0 AND 2
        AND
        -- Status: aberto, fechado ou cancelado.
        STATUS BETWEEN 0 AND 2
        AND
        -- Título obrigatório e sem espaços nas pontas.
        TRIM(TITULO) IS NOT NULL
        AND TITULO = TRIM(TITULO)
        AND
        -- Descrição, se informada, não pode ser vazia.
        (DESCRICAO IS NULL OR TRIM(DESCRICAO) IS NOT NULL)
        AND
        -- Aberto não possui data; fechado/cancelado possuem.
        (
            (STATUS = 0 AND FECHADO_EM IS NULL)
            OR (
                STATUS <> 0
                AND FECHADO_EM IS NOT NULL
                AND FECHADO_EM >= CRIADO_EM
            )
        )
        AND
        -- Vendedor e comprador não podem ser iguais.
        (
            ID_VENDEDOR IS NULL
            OR ID_COMPRADOR IS NULL
            OR ID_VENDEDOR <> ID_COMPRADOR
        )
        AND
        -- Venda/leilão exigem vendedor; compra exige comprador.
        (
            ((TIPO BETWEEN 0 AND 2) AND ID_VENDEDOR IS NOT NULL)
            OR (TIPO = 1 AND ID_COMPRADOR IS NOT NULL)
        )
        AND
        -- Fechado exige vendedor e comprador.
        (
            STATUS <> 1
            OR (ID_VENDEDOR IS NOT NULL AND ID_COMPRADOR IS NOT NULL)
        )
        AND
        -- Aberto permite apenas um dos participantes.
        (
            STATUS <> 0
            OR ID_VENDEDOR IS NULL
            OR ID_COMPRADOR IS NULL
        )
        AND
        -- Leilão exige lance mínimo e buyout válido.
        (
            (
                TIPO = 2
                AND MIN_LANCE IS NOT NULL
                AND MIN_LANCE > 0
                AND (
                    LANCE_DIRETO IS NULL
                    OR LANCE_DIRETO >= MIN_LANCE
                )
            )
            OR
            -- Outros tipos não possuem lances.
            (
                TIPO <> 2
                AND LANCE_DIRETO IS NULL
                AND MIN_LANCE IS NULL
            )
        )
    )
);

CREATE TABLE P2P_ANUNCIO_ITEM (
    ID_ANUNCIO_ITEM INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    ID_ANUNCIO INTEGER NOT NULL,
    ID_ITEM INTEGER NOT NULL,
    ACAO NUMBER(1,0) NOT NULL, -- 0 = ofertado, 1 = solicitado
    QNT NUMBER(3,0) NOT NULL,
    CONSTRAINT PK_P2P_ANUNCIO_ITEM PRIMARY KEY (ID_ANUNCIO_ITEM),
    CONSTRAINT FK_P2P_ANUNCIO_ITEM_ANUNCIO FOREIGN KEY (ID_ANUNCIO)
        REFERENCES P2P_ANUNCIO (ID_ANUNCIO),
    CONSTRAINT FK_P2P_ANUNCIO_ITEM_ITEM FOREIGN KEY (ID_ITEM)
        REFERENCES P2P_ITEM (ID_ITEM),

    CONSTRAINT CK_P2P_ANUNCIO_ITEM_REGRAS CHECK (
        -- Ação: ofertado ou solicitado.
        (ACAO BETWEEN 0 AND 1)
        AND
        -- Quantidade deve ser positiva.
        QNT > 0
    ),

    CONSTRAINT UK_P2P_ANUNCIO_ITEM_ANUNCIO_ITEM_ACAO
        UNIQUE (ID_ANUNCIO, ID_ITEM, ACAO)
);

CREATE TABLE P2P_ESPOLIO (
    ID_ESPOLIO INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    ID_PERSONAGEM INTEGER NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = jogador, 1 = NPC
    ID_ITEM INTEGER NOT NULL,
    PROBABILIDADE NUMBER(3,0),
    QNT NUMBER(3,0),
    QNT_MIN NUMBER(3,0),
    QNT_MAX NUMBER(3,0),
    CONSTRAINT PK_P2P_ESPOLIO PRIMARY KEY (ID_ESPOLIO),
    CONSTRAINT UK_P2P_ESPOLIO_PERSONAGEM_ITEM UNIQUE (ID_PERSONAGEM, ID_ITEM),
    CONSTRAINT FK_P2P_ESPOLIO_PERSONAGEM FOREIGN KEY (ID_PERSONAGEM, TIPO)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM, TIPO),
    CONSTRAINT FK_P2P_ESPOLIO_ITEM FOREIGN KEY (ID_ITEM)
        REFERENCES P2P_ITEM (ID_ITEM),

    CONSTRAINT CK_P2P_ESPOLIO_REGRAS CHECK (
        (
            -- Jogador: somente quantidade.
            TIPO = 0
            AND QNT IS NOT NULL
            AND QNT >= 0
            AND PROBABILIDADE IS NULL
            AND QNT_MIN IS NULL
            AND QNT_MAX IS NULL
        )
        OR
        (
            -- NPC: probabilidade e faixa de quantidade.
            TIPO = 1
            AND QNT IS NULL
            AND PROBABILIDADE IS NOT NULL
            AND PROBABILIDADE BETWEEN 1 AND 100
            AND QNT_MIN IS NOT NULL
            AND QNT_MIN >= 1
            AND QNT_MAX >= QNT_MIN
        )
    )
);

CREATE TABLE P2P_OCORRENCIA (
    ID_OCORRENCIA INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    ID_MOVIMENTACAO INTEGER NOT NULL,
    ID_ORIGEM INTEGER NOT NULL,
    ID_DESTINO INTEGER NOT NULL,
    ID_ESPOLIO INTEGER,
    ID_ANUNCIO_ITEM INTEGER,
    QNT NUMBER(3,0) NOT NULL,
    CONSTRAINT PK_P2P_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT UK_P2P_OCORRENCIA_ANUNCIO_ITEM UNIQUE (ID_ANUNCIO_ITEM),
    CONSTRAINT FK_P2P_OCORRENCIA_MOVIMENTACAO FOREIGN KEY (ID_MOVIMENTACAO)
        REFERENCES P2P_MOVIMENTACAO (ID_MOVIMENTACAO),
    CONSTRAINT FK_P2P_OCORRENCIA_ORIGEM FOREIGN KEY (ID_ORIGEM)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_OCORRENCIA_DESTINO FOREIGN KEY (ID_DESTINO)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_OCORRENCIA_ESPOLIO FOREIGN KEY (ID_ESPOLIO)
        REFERENCES P2P_ESPOLIO (ID_ESPOLIO),
    CONSTRAINT FK_P2P_OCORRENCIA_ANUNCIO_ITEM FOREIGN KEY (ID_ANUNCIO_ITEM)
        REFERENCES P2P_ANUNCIO_ITEM (ID_ANUNCIO_ITEM),

    CONSTRAINT CK_P2P_OCORRENCIA_REGRAS CHECK (
        -- Quantidade deve ser positiva.
        QNT > 0
        AND
        -- Origem e destino devem ser diferentes.
        ID_ORIGEM <> ID_DESTINO
        AND
        -- Ocorrência vem de espólio ou anúncio, nunca dos dois.
        (
            (ID_ESPOLIO IS NOT NULL AND ID_ANUNCIO_ITEM IS NULL)
            OR (ID_ESPOLIO IS NULL AND ID_ANUNCIO_ITEM IS NOT NULL)
        )
    )
);

CREATE TABLE P2P_HISTORICO_NEGOCIO (
    ID_HISTORICO INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1),
    ID_ANUNCIO INTEGER NOT NULL,
    ID_PERSONAGEM INTEGER NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = comprador, 1 = vendedor
    MENSAGEM VARCHAR2(200) NOT NULL,
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    STATUS NUMBER(1,0) NOT NULL,
    CONSTRAINT PK_P2P_HISTORICO_NEGOCIO PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_P2P_HISTORICO_NEGOCIO_ANUNCIO FOREIGN KEY (ID_ANUNCIO)
        REFERENCES P2P_ANUNCIO (ID_ANUNCIO),
    CONSTRAINT FK_P2P_HISTORICO_NEGOCIO_AUTOR FOREIGN KEY (ID_PERSONAGEM)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),

    CONSTRAINT CK_P2P_HISTORICO_NEGOCIO_REGRAS CHECK (
        -- Tipo: comprador ou vendedor.
        (TIPO BETWEEN 0 AND 1)
        AND
        -- Mensagem não pode ser vazia.
        TRIM(MENSAGEM) IS NOT NULL
    )
);