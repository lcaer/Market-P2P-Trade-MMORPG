CREATE TABLE P2P_MOVIMENTACAO (
    ID_MOVIMENTACAO INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    COD VARCHAR(7) NOT NULL,
    TIPO NUMBER(1,0) NOT NULL, -- 0 = batalha, 1 = negócio
    ID_ANUNCIO INTEGER,
    DESCRICAO VARCHAR(200) NOT NULL,
    CRIADO_EM DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_P2P_MOVIMENTACAO PRIMARY KEY (ID_MOVIMENTACAO),
    CONSTRAINT UK_P2P_MOVIMENTACAO_COD UNIQUE (COD),
    CONSTRAINT UK_P2P_MOVIMENTACAO_ID_TIPO UNIQUE (ID_MOVIMENTACAO, TIPO),
    CONSTRAINT FK_P2P_MOVIMENTACAO_ANUNCIO FOREIGN KEY (ID_ANUNCIO)
        REFERENCES P2P_ANUNCIO (ID_ANUNCIO),
    CONSTRAINT CK_P2P_MOVIMENTACAO_TIPO
        CHECK (TIPO BETWEEN 0 AND 1),
    CONSTRAINT CK_P2P_MOVIMENTACAO_LOOT_SEM_ANUNCIO
        CHECK (TIPO <> 0 OR ID_ANUNCIO IS NULL),
    CONSTRAINT CK_P2P_MOVIMENTACAO_NEGOCIACAO_ANUNCIO
        CHECK (TIPO <> 1 OR ID_ANUNCIO IS NOT NULL),
    CONSTRAINT CK_P2P_MOVIMENTACAO_COD_FORMATO
        CHECK (REGEXP_LIKE(COD, '^MOV[0-9]{4}$'))
);

CREATE TABLE P2P_OCORRENCIA (
    ID_OCORRENCIA INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    COD VARCHAR(7) NOT NULL,
    ID_MOVIMENTACAO INTEGER NOT NULL,
    TIPO_MOVIMENTACAO NUMBER(1,0) NOT NULL, -- 0 = batalha, 1 = negócio
    DESCRICAO VARCHAR(200) NOT NULL,
    ID_ORIGEM INTEGER NOT NULL,
    TIPO_ORIGEM NUMBER(1,0) NOT NULL, -- 0 = jogador, 1 = NPC
    ID_DESTINO INTEGER NOT NULL,
    ID_ESPOLIO INTEGER,
    ID_ANUNCIO_ITEM INTEGER,
    QNT NUMBER(3,0) NOT NULL,
    CONSTRAINT PK_P2P_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT UK_P2P_OCORRENCIA_COD UNIQUE (COD),
    CONSTRAINT UK_P2P_OCORRENCIA_ANUNCIO_ITEM UNIQUE (ID_ANUNCIO_ITEM),
    CONSTRAINT FK_P2P_OCORRENCIA_MOVIMENTACAO FOREIGN KEY (ID_MOVIMENTACAO, TIPO_MOVIMENTACAO)
        REFERENCES P2P_MOVIMENTACAO (ID_MOVIMENTACAO, TIPO),
    CONSTRAINT FK_P2P_OCORRENCIA_ORIGEM FOREIGN KEY (ID_ORIGEM, TIPO_ORIGEM)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM, TIPO),
    CONSTRAINT FK_P2P_OCORRENCIA_DESTINO FOREIGN KEY (ID_DESTINO)
        REFERENCES P2P_PERSONAGEM (ID_PERSONAGEM),
    CONSTRAINT FK_P2P_OCORRENCIA_ESPOLIO FOREIGN KEY (ID_ESPOLIO, ID_ORIGEM)
        REFERENCES P2P_ESPOLIO (ID_ESPOLIO, ID_PERSONAGEM),
    CONSTRAINT FK_P2P_OCORRENCIA_ANUNCIO_ITEM FOREIGN KEY (ID_ANUNCIO_ITEM)
        REFERENCES P2P_ANUNCIO_ITEM (ID_ANUNCIO_ITEM),
    CONSTRAINT CK_P2P_OCORRENCIA_ORIGEM_DESTINO_DIFERENTES
        CHECK (ID_ORIGEM <> ID_DESTINO),
    CONSTRAINT CK_P2P_OCORRENCIA_ORIGEM_UMA_CAUSA
        CHECK ((ID_ESPOLIO IS NOT NULL AND ID_ANUNCIO_ITEM IS NULL)
               OR (ID_ESPOLIO IS NULL AND ID_ANUNCIO_ITEM IS NOT NULL)),
    CONSTRAINT CK_P2P_OCORRENCIA_LOOT_USA_ESPOLIO
        CHECK (TIPO_MOVIMENTACAO <> 0 OR ID_ESPOLIO IS NOT NULL),
    CONSTRAINT CK_P2P_OCORRENCIA_NEGOCIACAO_USA_ANUNCIO_ITEM
        CHECK (TIPO_MOVIMENTACAO <> 1 OR ID_ANUNCIO_ITEM IS NOT NULL),
    CONSTRAINT CK_P2P_OCORRENCIA_ESPOLIO_SO_NPC
        CHECK (ID_ESPOLIO IS NULL OR TIPO_ORIGEM = 1),
    CONSTRAINT CK_P2P_OCORRENCIA_ANUNCIO_ITEM_SO_JOGADOR
        CHECK (ID_ANUNCIO_ITEM IS NULL OR TIPO_ORIGEM = 0),
    CONSTRAINT CK_P2P_OCORRENCIA_ORIGEM_POR_MOVIMENTACAO
        CHECK (
            (TIPO_MOVIMENTACAO = 0 AND TIPO_ORIGEM = 1)
            OR
            (TIPO_MOVIMENTACAO = 1 AND TIPO_ORIGEM = 0)
        ),
    CONSTRAINT CK_P2P_OCORRENCIA_QNT_POSITIVA
        CHECK (QNT > 0),
    CONSTRAINT CK_P2P_OCORRENCIA_COD_FORMATO
        CHECK (REGEXP_LIKE(COD, '^OCO[0-9]{4}$'))
);

