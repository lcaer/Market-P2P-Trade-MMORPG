-- FLUXO DE BATALHA 1: 50 OURO DO ESQUELETO PARA LEXIDRANI
DECLARE
    V_COD_MOV P2P_MOVIMENTACAO.COD%TYPE;
BEGIN
    ADD_P2P_MOVIMENTACAO_BATALHA('Luta: Esqueleto -> Lexidrani, 50 Ouro');

    SELECT MAX(COD) KEEP (DENSE_RANK LAST ORDER BY ID_MOVIMENTACAO)
      INTO V_COD_MOV
      FROM P2P_MOVIMENTACAO
     WHERE DESCRICAO = 'Luta: Esqueleto -> Lexidrani, 50 Ouro'
       AND TIPO = 0;

    UPDATE P2P_ESPOLIO
       SET QNT = QNT + 50
     WHERE ID_PERSONAGEM = (SELECT ID_PERSONAGEM FROM P2P_PERSONAGEM WHERE NICKNAME = 'lexidrani')
       AND ID_ITEM = (SELECT ID_ITEM FROM P2P_ITEM WHERE COD = 'OUROO');

    ADD_P2P_OCORRENCIA(V_COD_MOV, 'Transferencia de 50 Ouro do Esqueleto para Lexidrani',
                       'Esqueleto', 'lexidrani', 'OUROO', 50);
END;
