CREATE OR REPLACE PROCEDURE DEL_P2P_CATEGORIA (P_TIPO IN P2P_CATEGORIA.TIPO%TYPE) IS
                                               
BEGIN
    DELETE FROM P2P_CATEGORIA
        WHERE TIPO = P_TIPO;
END DEL_P2P_CATEGORIA;
/

BEGIN
