CREATE OR REPLACE PROCEDURE UPD_P2P_CATEGORIA(P_NOME IN P2P_CATEGORIA.NOME%TYPE,
                                              P_NOVO_TIPO IN P2P_CATEGORIA.TIPO%TYPE) IS
BEGIN
    UPDATE P2P_CATEGORIA
        SET TIPO = P_NOVO_TIPO
        WHERE NOME = P_NOME;
