--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE DEL_P2P_USUARIO (
    P_UNAME IN P2P_USUARIO.USERNAME%TYPE,
    P_EMAIL IN P2P_USUARIO.EMAIL%TYPE,
    P_SENHA IN P2P_USUARIO.SENHA%TYPE) 
    IS
BEGIN
    DELETE FROM P2P_USUARIO
    WHERE USERNAME = P_UNAME AND EMAIL = P_EMAIL AND SENHA = P_SENHA;
END;

