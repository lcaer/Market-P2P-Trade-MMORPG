--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_HISTORICO_NEGOCIO (
    P_COD_ANUNCIO IN P2P_ANUNCIO.COD%TYPE,
    P_NICK        IN P2P_PERSONAGEM.NICKNAME%TYPE,
    P_MENSAGEM    IN P2P_HISTORICO_NEGOCIO.MENSAGEM%TYPE
) IS
    V_ID_ANUNCIO     P2P_ANUNCIO.ID_ANUNCIO%TYPE;
    V_ID_ANUNCIANTE  P2P_ANUNCIO.ID_ANUNCIANTE%TYPE;
    V_ID_PERSONAGEM  P2P_PERSONAGEM.ID_PERSONAGEM%TYPE;
    V_TIPO           P2P_HISTORICO_NEGOCIO.TIPO%TYPE;
BEGIN
    SELECT ID_ANUNCIO, ID_ANUNCIANTE
      INTO V_ID_ANUNCIO, V_ID_ANUNCIANTE
      FROM P2P_ANUNCIO
     WHERE COD = P_COD_ANUNCIO;

    SELECT ID_PERSONAGEM
      INTO V_ID_PERSONAGEM
      FROM P2P_PERSONAGEM
     WHERE NICKNAME = P_NICK;

    IF V_ID_PERSONAGEM = V_ID_ANUNCIANTE 
        THEN V_TIPO := 0;
        ELSE V_TIPO := 1;
    END IF;

    INSERT INTO P2P_HISTORICO_NEGOCIO (ID_ANUNCIO, ID_PERSONAGEM, TIPO,
                                       MENSAGEM, COD)
    VALUES (V_ID_ANUNCIO, V_ID_PERSONAGEM, V_TIPO, P_MENSAGEM,
            'HIS' || LPAD(SEQ_P2P_HISTORICO_NEGOCIO_COD.NEXTVAL, 4, '0'));
END;
