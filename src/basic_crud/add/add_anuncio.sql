--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_ANUNCIO_COMPRA (
    P_NICK_ANUNCIANTE IN P2P_PERSONAGEM.NICKNAME%TYPE,
    P_TITULO IN P2P_ANUNCIO.TITULO%TYPE,
    P_DESCRICAO IN P2P_ANUNCIO.DESCRICAO%TYPE
) IS
    V_ID_ANUNCIANTE P2P_ANUNCIO.ID_ANUNCIANTE%TYPE;
BEGIN
    SELECT ID_PERSONAGEM
      INTO V_ID_ANUNCIANTE
      FROM P2P_PERSONAGEM
     WHERE NICKNAME = P_NICK_ANUNCIANTE;

    INSERT INTO P2P_ANUNCIO (ID_ANUNCIANTE, TIPO, TITULO, DESCRICAO, COD)
    VALUES (V_ID_ANUNCIANTE, 2, P_TITULO, P_DESCRICAO,
            'ADS' || LPAD(SEQ_P2P_ANUNCIO_COD.NEXTVAL, 4, '0'));
END;
