--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_ANUNCIO_ITEM_OFERTADO (
    P_COD_ANUNCIO IN P2P_ANUNCIO.COD%TYPE,
    P_COD_ITEM IN P2P_ITEM.COD%TYPE,
    P_QNT IN P2P_ANUNCIO_ITEM.QNT%TYPE
) IS
    V_ID_ANUNCIO P2P_ANUNCIO_ITEM.ID_ANUNCIO%TYPE;
    V_ID_ITEM P2P_ANUNCIO_ITEM.ID_ITEM%TYPE;
BEGIN
    SELECT ID_ANUNCIO
      INTO V_ID_ANUNCIO
      FROM P2P_ANUNCIO
     WHERE COD = P_COD_ANUNCIO;

    SELECT ID_ITEM
      INTO V_ID_ITEM
      FROM P2P_ITEM
     WHERE COD = P_COD_ITEM;

    INSERT INTO P2P_ANUNCIO_ITEM (ID_ANUNCIO, ID_ITEM, ACAO, QNT, COD)
    VALUES (V_ID_ANUNCIO, V_ID_ITEM, 0, P_QNT,
            'AIT' || LPAD(SEQ_P2P_ANUNCIO_ITEM_COD.NEXTVAL, 4, '0'));
END;
