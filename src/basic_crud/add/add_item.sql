--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_ITEM (
    P_COD_CATEGORIA IN P2P_CATEGORIA.COD%TYPE,
    P_RARIDADE IN P2P_ITEM.RARIDADE%TYPE,
    P_NOME IN P2P_ITEM.NOME%TYPE,
    P_DESCRICAO IN P2P_ITEM.DESCRICAO%TYPE,
    P_COD IN P2P_ITEM.COD%TYPE
) IS
    V_ID_CATEGORIA P2P_ITEM.ID_CATEGORIA%TYPE;
BEGIN
    SELECT ID_CATEGORIA
      INTO V_ID_CATEGORIA
      FROM P2P_CATEGORIA
     WHERE COD = P_COD_CATEGORIA;

    INSERT INTO P2P_ITEM (ID_CATEGORIA, RARIDADE, NOME, DESCRICAO, COD)
    VALUES (V_ID_CATEGORIA, P_RARIDADE, P_NOME, P_DESCRICAO, P_COD);
END;
