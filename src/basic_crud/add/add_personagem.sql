CREATE OR REPLACE PROCEDURE ADD_P2P_PERSONAGEM_NPC (
    P_NICK IN P2P_PERSONAGEM.NICKNAME%TYPE
) IS
BEGIN
    INSERT INTO P2P_PERSONAGEM (TIPO, NICKNAME)
    VALUES (1, P_NICK);
END;
