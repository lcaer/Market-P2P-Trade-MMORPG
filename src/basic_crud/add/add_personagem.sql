--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_PERSONAGEM_JOGADOR (
    P_UNAME IN P2P_USUARIO.USERNAME%TYPE,
    P_NICK IN P2P_PERSONAGEM.NICKNAME%TYPE
) IS
    V_ID_USER P2P_PERSONAGEM.ID_USUARIO%TYPE;
BEGIN
    SELECT ID_USUARIO
      INTO V_ID_USER
      FROM P2P_USUARIO
     WHERE USERNAME = P_UNAME;

    INSERT INTO P2P_PERSONAGEM (ID_USUARIO, TIPO, NICKNAME, NIVEL)
    VALUES (V_ID_USER, 0, P_NICK, 0);
END;
/

