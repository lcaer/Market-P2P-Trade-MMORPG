--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_ESPOLIO_JOGADOR (
    P_NICK IN P2P_PERSONAGEM.NICKNAME%TYPE,
    P_COD_ITEM IN P2P_ITEM.COD%TYPE,
    P_QNT IN P2P_ESPOLIO.QNT%TYPE
) IS
    V_ID_PERSONAGEM P2P_ESPOLIO.ID_PERSONAGEM%TYPE;
    V_ID_ITEM P2P_ESPOLIO.ID_ITEM%TYPE;
BEGIN
    SELECT ID_PERSONAGEM
      INTO V_ID_PERSONAGEM
      FROM P2P_PERSONAGEM
     WHERE NICKNAME = P_NICK
       AND TIPO = 0;

    SELECT ID_ITEM
      INTO V_ID_ITEM
      FROM P2P_ITEM
     WHERE COD = P_COD_ITEM;

    INSERT INTO P2P_ESPOLIO (ID_PERSONAGEM, TIPO, ID_ITEM, QNT, COD)
    VALUES (V_ID_PERSONAGEM, 0, V_ID_ITEM, P_QNT,
            'ESP' || LPAD(SEQ_P2P_ESPOLIO_COD.NEXTVAL, 4, '0'));
END;
