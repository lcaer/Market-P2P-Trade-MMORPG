CREATE OR REPLACE PROCEDURE ADD_P2P_ESPOLIO_NPC (
    P_NICK_NPC IN P2P_PERSONAGEM.NICKNAME%TYPE,
    P_COD_ITEM IN P2P_ITEM.COD%TYPE,
    P_PROBABILIDADE IN P2P_ESPOLIO.PROBABILIDADE%TYPE,
    P_QNT_MIN IN P2P_ESPOLIO.QNT_MIN%TYPE,
    P_QNT_MAX IN P2P_ESPOLIO.QNT_MAX%TYPE
) IS
    V_ID_PERSONAGEM P2P_ESPOLIO.ID_PERSONAGEM%TYPE;
    V_ID_ITEM P2P_ESPOLIO.ID_ITEM%TYPE;
BEGIN
    SELECT ID_PERSONAGEM
      INTO V_ID_PERSONAGEM
      FROM P2P_PERSONAGEM
     WHERE NICKNAME = P_NICK_NPC
       AND TIPO = 1;

    SELECT ID_ITEM
      INTO V_ID_ITEM
      FROM P2P_ITEM
     WHERE COD = P_COD_ITEM;

    INSERT INTO P2P_ESPOLIO (
        ID_PERSONAGEM, TIPO, ID_ITEM, PROBABILIDADE, QNT_MIN, QNT_MAX, COD
    )
    VALUES (
        V_ID_PERSONAGEM, 1, V_ID_ITEM, P_PROBABILIDADE, P_QNT_MIN, P_QNT_MAX,
        'ESP' || LPAD(SEQ_P2P_ESPOLIO_COD.NEXTVAL, 4, '0')
    );
END;
