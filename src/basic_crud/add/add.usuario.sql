--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_USUARIO (
    P_NOME IN P2P_USUARIO.NOME%TYPE, 
    P_UNAME IN P2P_USUARIO.USERNAME%TYPE,
    P_EMAIL IN P2P_USUARIO.EMAIL%TYPE,
    P_SENHA IN P2P_USUARIO.SENHA%TYPE) 
    IS
BEGIN
    INSERT INTO P2P_USUARIO (NOME, USERNAME, EMAIL, SENHA) 
    VALUES (P_NOME, P_UNAME,P_EMAIL,P_SENHA);
END;

