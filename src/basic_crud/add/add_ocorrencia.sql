--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_OCORRENCIA (
    P_COD_MOVIMENTACAO IN P2P_MOVIMENTACAO.COD%TYPE,
    P_DESCRICAO IN P2P_OCORRENCIA.DESCRICAO%TYPE,
    P_NICK_ORIGEM IN P2P_PERSONAGEM.NICKNAME%TYPE,
    P_NICK_DESTINO IN P2P_PERSONAGEM.NICKNAME%TYPE,
    P_COD_ITEM IN P2P_ITEM.COD%TYPE,
    P_QNT IN P2P_OCORRENCIA.QNT%TYPE,
    P_ACAO IN P2P_ANUNCIO_ITEM.ACAO%TYPE DEFAULT 0
) IS
    V_ID_MOVIMENTACAO P2P_OCORRENCIA.ID_MOVIMENTACAO%TYPE;
    V_TIPO_MOVIMENTACAO P2P_OCORRENCIA.TIPO_MOVIMENTACAO%TYPE;
    V_ID_ANUNCIO P2P_MOVIMENTACAO.ID_ANUNCIO%TYPE;
    V_ID_ORIGEM P2P_OCORRENCIA.ID_ORIGEM%TYPE;
    V_TIPO_ORIGEM P2P_OCORRENCIA.TIPO_ORIGEM%TYPE;
    V_ID_DESTINO P2P_OCORRENCIA.ID_DESTINO%TYPE;
    V_ID_ITEM P2P_ITEM.ID_ITEM%TYPE;
    V_ID_ESPOLIO P2P_OCORRENCIA.ID_ESPOLIO%TYPE;
    V_ID_ANUNCIO_ITEM P2P_OCORRENCIA.ID_ANUNCIO_ITEM%TYPE;
BEGIN
    SELECT ID_MOVIMENTACAO, TIPO, ID_ANUNCIO
      INTO V_ID_MOVIMENTACAO, V_TIPO_MOVIMENTACAO, V_ID_ANUNCIO
      FROM P2P_MOVIMENTACAO
     WHERE COD = P_COD_MOVIMENTACAO;

    SELECT ID_PERSONAGEM, TIPO
      INTO V_ID_ORIGEM, V_TIPO_ORIGEM
      FROM P2P_PERSONAGEM
     WHERE NICKNAME = P_NICK_ORIGEM;

    SELECT ID_PERSONAGEM
      INTO V_ID_DESTINO
      FROM P2P_PERSONAGEM
     WHERE NICKNAME = P_NICK_DESTINO;

    SELECT ID_ITEM
      INTO V_ID_ITEM
      FROM P2P_ITEM
     WHERE COD = P_COD_ITEM;

    V_ID_ESPOLIO := NULL;
    V_ID_ANUNCIO_ITEM := NULL;

    IF V_TIPO_MOVIMENTACAO = 0 AND V_TIPO_ORIGEM = 1 THEN
        SELECT ID_ESPOLIO
          INTO V_ID_ESPOLIO
          FROM P2P_ESPOLIO
         WHERE ID_PERSONAGEM = V_ID_ORIGEM
           AND ID_ITEM = V_ID_ITEM;

    ELSIF V_TIPO_MOVIMENTACAO = 1 AND V_TIPO_ORIGEM = 0 THEN
        SELECT ID_ANUNCIO_ITEM
          INTO V_ID_ANUNCIO_ITEM
          FROM P2P_ANUNCIO_ITEM
         WHERE ID_ANUNCIO = V_ID_ANUNCIO
           AND ID_ITEM = V_ID_ITEM
           AND ACAO = P_ACAO;

    END IF;

    INSERT INTO P2P_OCORRENCIA (
        ID_MOVIMENTACAO, TIPO_MOVIMENTACAO, DESCRICAO,
        ID_ORIGEM, TIPO_ORIGEM, ID_DESTINO, ID_ESPOLIO,
        ID_ANUNCIO_ITEM, QNT, COD
    )
    VALUES (
        V_ID_MOVIMENTACAO, V_TIPO_MOVIMENTACAO, P_DESCRICAO,
        V_ID_ORIGEM, V_TIPO_ORIGEM, V_ID_DESTINO, V_ID_ESPOLIO,
        V_ID_ANUNCIO_ITEM, P_QNT,
        'OCO' || LPAD(SEQ_P2P_OCORRENCIA_COD.NEXTVAL, 4, '0')
    );
END;
