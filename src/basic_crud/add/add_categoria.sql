--SET SERVEROUTPUT ON;
CREATE OR REPLACE PROCEDURE ADD_P2P_CATEGORIA_MATERIA_PRIMA (
    P_NOME IN P2P_CATEGORIA.NOME%TYPE,
    P_COD IN P2P_CATEGORIA.COD%TYPE
) IS
BEGIN
    INSERT INTO P2P_CATEGORIA (NOME, TIPO, COD)
    VALUES (P_NOME, 0, P_COD);
END;
/

