CREATE OR REPLACE PROCEDURE ADD_P2P_MOVIMENTACAO_BATALHA (
    P_DESCRICAO IN P2P_MOVIMENTACAO.DESCRICAO%TYPE
) IS
BEGIN
    INSERT INTO P2P_MOVIMENTACAO (TIPO, DESCRICAO, COD)
    VALUES (0, P_DESCRICAO,
            'MOV' || LPAD(SEQ_P2P_MOVIMENTACAO_COD.NEXTVAL, 4, '0'));
END;
/

