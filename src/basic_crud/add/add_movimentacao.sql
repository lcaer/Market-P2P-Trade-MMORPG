CREATE OR REPLACE PROCEDURE ADD_P2P_MOVIMENTACAO_NEGOCIO (
    P_COD_ANUNCIO IN P2P_ANUNCIO.COD%TYPE,
    P_DESCRICAO IN P2P_MOVIMENTACAO.DESCRICAO%TYPE
) IS
    V_ID_ANUNCIO P2P_MOVIMENTACAO.ID_ANUNCIO%TYPE;
BEGIN
    SELECT ID_ANUNCIO
      INTO V_ID_ANUNCIO
      FROM P2P_ANUNCIO
     WHERE COD = P_COD_ANUNCIO;

    INSERT INTO P2P_MOVIMENTACAO (TIPO, ID_ANUNCIO, DESCRICAO, COD)
    VALUES (1, V_ID_ANUNCIO, P_DESCRICAO,
            'MOV' || LPAD(SEQ_P2P_MOVIMENTACAO_COD.NEXTVAL, 4, '0'));
END;
/
