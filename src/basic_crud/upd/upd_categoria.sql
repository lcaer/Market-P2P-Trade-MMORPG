CREATE OR REPLACE PROCEDURE UPD_P2P_CATEGORIA_POR_COD (
    P_NOME IN P2P_CATEGORIA.NOME%TYPE,
    P_TIPO IN P2P_CATEGORIA.TIPO%TYPE,
    P_COD IN P2P_CATEGORIA.COD%TYPE
) IS
BEGIN
    UPDATE P2P_CATEGORIA
        SET NOME = P_NOME,
            TIPO = P_TIPO
    WHERE COD = P_COD;
END;

