CREATE OR REPLACE PROCEDURE UPD_P2P_USUARIO_POR_EMAIL (
    P_NOME IN P2P_USUARIO.NOME%TYPE, 
    P_UNAME IN P2P_USUARIO.USERNAME%TYPE,
    P_EMAIL IN P2P_USUARIO.EMAIL%TYPE,
    P_SENHA IN P2P_USUARIO.SENHA%TYPE) 
    IS
BEGIN
    UPDATE P2P_USUARIO
        SET NOME = P_NOME,
            USERNAME = P_UNAME,
            SENHA = P_SENHA
    WHERE EMAIL = P_EMAIL;
END;

